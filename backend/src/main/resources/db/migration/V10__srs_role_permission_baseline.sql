-- Add the SRS admission workflow permissions without conflating them with
-- unrestricted student-record permissions.
INSERT IGNORE INTO permissions (code, description, module) VALUES
    ('ADMISSION:READ', 'Read applicant and admission workflow records', 'ADMISSION'),
    ('ADMISSION:CREATE', 'Create and submit admission applications', 'ADMISSION'),
    ('ADMISSION:UPDATE', 'Review and decide admission applications', 'ADMISSION')
;

