    private ExamSummaryResponse createAndPublishExam(BigDecimal student1Marks, BigDecimal student2Marks) {
        ExamSummaryResponse exam = createExamWithSchedule();

        SaveMarksRequest saveReq = new SaveMarksRequest(
                1L, 1L, List.of(
                        new StudentMarkInput(1L, student1Marks, "PRESENT", null),
                        new StudentMarkInput(2L, student2Marks, "PRESENT", null)
                )
        );
        service.saveDraftMarks(exam.id(), saveReq, teacher1);
        SubmissionSummaryResponse sub = service.submitMarks(exam.id(), new SubmitMarksRequest(1L, 1L), teacher1);
        service.reviewSubmission(sub.id(), "APPROVE", "Approved", admin);
        return service.publishResults(exam.id(), admin);
    }
