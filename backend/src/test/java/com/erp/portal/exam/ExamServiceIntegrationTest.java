    @Test
    void testResultPublicationAndUnauthorizedDenial() {
        ExamSummaryResponse exam = createExamWithSchedule();

        SaveMarksRequest saveReq = new SaveMarksRequest(
                1L, 1L, List.of(
                        new StudentMarkInput(1L, BigDecimal.valueOf(92.0), "PRESENT", null),
                        new StudentMarkInput(2L, BigDecimal.valueOf(88.0), "PRESENT", null)
                )
        );
        service.saveDraftMarks(exam.id(), saveReq, teacher1);
        SubmissionSummaryResponse sub = service.submitMarks(exam.id(), new SubmitMarksRequest(1L, 1L), teacher1);

        // Non-admin (teacher, management) cannot publish
        assertThrows(ExamException.class, () -> service.publishResults(exam.id(), teacher1));
        assertThrows(ExamException.class, () -> service.publishResults(exam.id(), management));

        // Admin cannot publish until submission is approved
        assertThrows(ExamException.class, () -> service.publishResults(exam.id(), admin));

        // Admin approves submission
        service.reviewSubmission(sub.id(), "APPROVE", "Approved by admin", admin);

        // Now admin publishes successfully
        ExamSummaryResponse published = service.publishResults(exam.id(), admin);
        assertEquals("PUBLISHED", published.status());
    }

