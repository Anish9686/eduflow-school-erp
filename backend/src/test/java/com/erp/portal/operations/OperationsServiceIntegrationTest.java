package com.erp.portal.operations;

import com.erp.portal.security.SecurityPrincipal;
import org.h2.jdbcx.JdbcDataSource;
import org.junit.jupiter.api.BeforeEach;
import org.junit.jupiter.api.Test;
import org.springframework.jdbc.core.JdbcTemplate;

import java.math.BigDecimal;
import java.time.LocalDate;
import java.util.List;
import java.util.Set;

import static org.junit.jupiter.api.Assertions.assertEquals;
import static org.junit.jupiter.api.Assertions.assertThrows;

class OperationsServiceIntegrationTest {
    private OperationsService service;
    private JdbcTemplate jdbc;

    @BeforeEach
    void setUp() {
        JdbcDataSource dataSource = new JdbcDataSource();
        dataSource.setURL("jdbc:h2:mem:operations-test-" + System.nanoTime() + ";DB_CLOSE_DELAY=-1;MODE=MySQL");
        dataSource.setUser("sa");
        dataSource.setPassword("");
        jdbc = new JdbcTemplate(dataSource);
        jdbc.execute("CREATE TABLE inventory_items (id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, name VARCHAR(200), code VARCHAR(50) UNIQUE, category VARCHAR(100), unit VARCHAR(20), current_stock INT, min_stock_level INT, description VARCHAR(500), updated_at TIMESTAMP)");
        jdbc.execute("CREATE TABLE stock_movements (id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, item_id BIGINT, movement_type VARCHAR(20), quantity INT, reference_no VARCHAR(80), remarks VARCHAR(500), moved_by BIGINT, moved_at TIMESTAMP)");
        jdbc.execute("CREATE TABLE library_items (id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, isbn VARCHAR(20), title VARCHAR(255), author VARCHAR(200), category VARCHAR(100), total_copies INT, available_copies INT, rack_location VARCHAR(50), updated_at TIMESTAMP)");
        jdbc.execute("CREATE TABLE library_issues (id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, item_id BIGINT, borrower_type VARCHAR(20), student_id BIGINT, issued_date DATE, due_date DATE, returned_date DATE, fine_amount DECIMAL(8,2), status VARCHAR(20), issued_by BIGINT)");
        jdbc.execute("CREATE TABLE hostel_rooms (id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, room_no VARCHAR(20) UNIQUE, floor VARCHAR(10), block VARCHAR(20), capacity INT, room_type VARCHAR(20), is_active TINYINT)");
        jdbc.execute("CREATE TABLE hostel_allocations (id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, room_id BIGINT, student_id BIGINT, session_id BIGINT, bed_no VARCHAR(10), allotted_from DATE, allotted_to DATE, status VARCHAR(20), allocated_by BIGINT)");
        jdbc.execute("CREATE TABLE support_tickets (id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, title VARCHAR(255), description TEXT, category VARCHAR(100), priority VARCHAR(20), status VARCHAR(20), raised_by BIGINT, assigned_to BIGINT, created_at TIMESTAMP, updated_at TIMESTAMP)");
        jdbc.execute("CREATE TABLE ticket_comments (id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, ticket_id BIGINT, comment TEXT, commented_by BIGINT, created_at TIMESTAMP)");
        service = new OperationsService(new OperationsRepository(jdbc));
    }

    @Test
    void stockMovementRejectsNegativeBalanceByDefault() {
        long item = service.createItem(new OperationsDtos.CreateItemRequest("Notebook", "N-1", "Office", "PCS", 1, 0, null), actor()).id();
        assertThrows(OperationsException.class, () -> service.stockMovement(item, new OperationsDtos.StockMovementRequest("OUT", 2, null, null), actor()));
        assertEquals(1, jdbc.queryForObject("SELECT current_stock FROM inventory_items WHERE id = ?", Integer.class, item));
    }

    @Test
    void stockMovementAllowsExplicitNegativeConfiguration() {
        long item = service.createItem(new OperationsDtos.CreateItemRequest("Notebook", "N-2", "Office", "PCS", 1, 0, null), actor()).id();
        service.stockMovement(item, new OperationsDtos.StockMovementRequest("OUT", 2, null, null), actor(), true);
        assertEquals(-1, jdbc.queryForObject("SELECT current_stock FROM inventory_items WHERE id = ?", Integer.class, item));
    }

    @Test
    void issueAndReturnUpdateAvailabilityAndFineHistory() {
        long item = service.createLibraryItem(new OperationsDtos.CreateLibraryItemRequest("978", "Book", "Author", "Books", 1, 1, "A1"), actor()).id();
        long issue = service.issueLibrary(item, new OperationsDtos.IssueRequest("STUDENT", 9L, LocalDate.now(), LocalDate.now().plusDays(7), null), actor()).id();
        assertEquals(0, jdbc.queryForObject("SELECT available_copies FROM library_items WHERE id = ?", Integer.class, item));
        service.returnLibrary(issue, new OperationsDtos.ReturnRequest(LocalDate.now(), new BigDecimal("2.50"), "Good"), actor());
        assertEquals(1, jdbc.queryForObject("SELECT available_copies FROM library_items WHERE id = ?", Integer.class, item));
        assertEquals(new BigDecimal("2.50"), jdbc.queryForObject("SELECT fine_amount FROM library_issues WHERE id = ?", BigDecimal.class, issue));
    }

    @Test
    void hostelAllocationRejectsDoubleActiveAllocation() {
        long room = service.createRoom(new OperationsDtos.CreateRoomRequest("R1", "1", "A", 1, "SINGLE", true), actor()).id();
        service.allocateHostel(room, new OperationsDtos.AllocationRequest(10L, 1L, LocalDate.now(), null, "ACTIVE"), actor());
        assertThrows(OperationsException.class, () -> service.allocateHostel(room, new OperationsDtos.AllocationRequest(11L, 1L, LocalDate.now(), null, "ACTIVE"), actor()));
    }

    @Test
    void createdHostelRoomIsVisibleInRoomList() {
        var created = service.createRoom(new OperationsDtos.CreateRoomRequest("R2", "2", "B", 2, "DOUBLE", true), actor());
        assertEquals(List.of(created), service.rooms());
    }

    @Test
    void supportAgentOnlySeesAndAssignsTicketsWithinTheirScope() {
        jdbc.update("INSERT INTO support_tickets(title,description,category,priority,status,raised_by,assigned_to,created_at,updated_at) VALUES('Mine','Details','IT','LOW','OPEN',1,1,CURRENT_TIMESTAMP,CURRENT_TIMESTAMP)");
        jdbc.update("INSERT INTO support_tickets(title,description,category,priority,status,raised_by,assigned_to,created_at,updated_at) VALUES('Other','Details','IT','LOW','OPEN',2,2,CURRENT_TIMESTAMP,CURRENT_TIMESTAMP)");
        SecurityPrincipal agent = new SecurityPrincipal(1, "agent", "Agent", List.of("SUPPORT_AGENT"), Set.of("SUPPORT:READ", "SUPPORT:MANAGE"), "hash");

        assertEquals(List.of("Mine"), service.tickets(agent).stream().map(OperationsDtos.TicketResponse::title).toList());
        var created = service.createTicket(new OperationsDtos.CreateTicketRequest("Created", "Details", "IT", "LOW", "OPEN", null), agent);
        assertEquals(1L, created.assignedTo());
        assertEquals(java.util.Set.of("Created", "Mine"), new java.util.HashSet<>(service.tickets(agent).stream().map(OperationsDtos.TicketResponse::title).toList()));
        assertThrows(OperationsException.class, () -> service.createTicket(
                new OperationsDtos.CreateTicketRequest("Escalated", "Details", "IT", "LOW", "OPEN", "2"), agent));
    }

    private SecurityPrincipal actor() {
        return new SecurityPrincipal(1L, "admin", "Admin", List.of("ADMIN"), Set.of(
                "INVENTORY:MANAGE", "LIBRARY:MANAGE", "LIBRARY:ISSUE", "LIBRARY:RETURN",
                "HOSTEL:MANAGE", "SUPPORT:MANAGE"), "hash");
    }
}
