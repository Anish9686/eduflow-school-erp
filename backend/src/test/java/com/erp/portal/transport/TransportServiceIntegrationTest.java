    @Test
    void reassignStudentPreservesHistoryAndFreesSeat() {
        var routeReq = new TransportDtos.CreateRouteRequest("Route Flow", "RF-01", null, List.of(), "MAIN");
        long routeId = service.createRoute(routeReq, superAdmin, mockRequest).id();

        var bus1 = service.createBus(new TransportDtos.CreateBusRequest("Bus 10", "RJ14 XX 8001", null, "STD", 5, routeId, null, null, "MAIN"), superAdmin, mockRequest).id();
        var bus2 = service.createBus(new TransportDtos.CreateBusRequest("Bus 20", "RJ14 XX 8002", null, "STD", 5, routeId, null, null, "MAIN"), superAdmin, mockRequest).id();

        var assignment = service.assignStudent(new TransportDtos.AssignStudentRequest(10L, bus1, routeId, null, null, LocalDate.now(), null), superAdmin, mockRequest);
        assertEquals(1, repository.getBusActiveOccupancy(bus1));
        assertEquals(0, repository.getBusActiveOccupancy(bus2));

        // Reassign to bus2
        service.reassignStudent(assignment.id(), new TransportDtos.ReassignStudentRequest(bus2, routeId, null, null, "Family moved house"), superAdmin, mockRequest);

        assertEquals(0, repository.getBusActiveOccupancy(bus1));
        assertEquals(1, repository.getBusActiveOccupancy(bus2));

        // Check history
        List<TransportDtos.AssignmentHistoryResponse> history = service.getHistory(10L, null, 10);
        assertEquals(2, history.size());
        assertEquals("REASSIGNED", history.get(0).action());
        assertEquals("ASSIGNED", history.get(1).action());
    }

