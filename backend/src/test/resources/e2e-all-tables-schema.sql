CREATE TABLE IF NOT EXISTS academic_sessions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code VARCHAR(30) NOT NULL UNIQUE,
    name VARCHAR(100) NOT NULL,
    start_date DATE NOT NULL,
    end_date DATE NOT NULL,
    is_active BOOLEAN NOT NULL DEFAULT FALSE,
    created_at TIMESTAMP
);

CREATE TABLE IF NOT EXISTS classes (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(50) NOT NULL UNIQUE,
    order_seq INT NOT NULL DEFAULT 0,
    created_at TIMESTAMP
);

CREATE TABLE IF NOT EXISTS sections (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    class_id BIGINT NOT NULL,
    name VARCHAR(10) NOT NULL,
    capacity INT,
    room_no VARCHAR(20),
    created_at TIMESTAMP
);

CREATE TABLE IF NOT EXISTS subjects (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code VARCHAR(30) NOT NULL UNIQUE,
    name VARCHAR(100) NOT NULL,
    description VARCHAR(255),
    created_at TIMESTAMP
);

CREATE TABLE IF NOT EXISTS class_subjects (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    session_id BIGINT NOT NULL,
    class_id BIGINT NOT NULL,
    subject_id BIGINT NOT NULL,
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMP
);

CREATE TABLE IF NOT EXISTS teacher_assignments (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    session_id BIGINT NOT NULL,
    section_id BIGINT NOT NULL,
    subject_id BIGINT NOT NULL,
    staff_id BIGINT NOT NULL,
    status VARCHAR(20) NOT NULL DEFAULT 'ACTIVE',
    assigned_at TIMESTAMP
);

CREATE TABLE IF NOT EXISTS timetable (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    session_id BIGINT NOT NULL,
    class_id BIGINT NOT NULL,
    section_id BIGINT NOT NULL,
    subject_id BIGINT NOT NULL,
    teacher_id BIGINT,
    day_of_week INT NOT NULL,
    start_time TIME NOT NULL,
    end_time TIME NOT NULL,
    room_no VARCHAR(20),
    created_at TIMESTAMP
);

CREATE TABLE IF NOT EXISTS staff (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    employee_no VARCHAR(50) NOT NULL UNIQUE,
    first_name VARCHAR(100) NOT NULL,
    last_name VARCHAR(100),
    email VARCHAR(254),
    phone VARCHAR(30),
    department VARCHAR(100),
    status VARCHAR(20) NOT NULL DEFAULT 'ACTIVE',
    user_id BIGINT,
    created_at TIMESTAMP
);

CREATE TABLE IF NOT EXISTS students (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    admission_no VARCHAR(50) NOT NULL UNIQUE,
    first_name VARCHAR(100) NOT NULL,
    last_name VARCHAR(100),
    date_of_birth DATE,
    gender VARCHAR(20),
    blood_group VARCHAR(10),
    religion VARCHAR(50),
    category VARCHAR(50),
    phone VARCHAR(30),
    email VARCHAR(254),
    address CLOB,
    photo_url VARCHAR(500),
    status VARCHAR(20) NOT NULL DEFAULT 'ACTIVE',
    admission_date DATE,
    exit_date DATE,
    exit_reason VARCHAR(500),
    user_id BIGINT,
    created_by BIGINT,
    updated_by BIGINT,
    created_at TIMESTAMP,
    updated_at TIMESTAMP
);

CREATE TABLE IF NOT EXISTS guardians (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(150) NOT NULL,
    phone VARCHAR(30),
    email VARCHAR(254),
    address CLOB,
    occupation VARCHAR(100),
    user_id BIGINT,
    created_at TIMESTAMP
);

CREATE TABLE IF NOT EXISTS student_guardians (
    student_id BIGINT NOT NULL,
    guardian_id BIGINT NOT NULL,
    relation VARCHAR(30) NOT NULL,
    is_primary BOOLEAN NOT NULL DEFAULT FALSE,
    PRIMARY KEY (student_id, guardian_id)
);

CREATE TABLE IF NOT EXISTS student_documents (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    student_id BIGINT NOT NULL,
    doc_type VARCHAR(60) NOT NULL,
    file_name VARCHAR(255) NOT NULL,
    file_path VARCHAR(1000) NOT NULL,
    file_size_bytes BIGINT,
    mime_type VARCHAR(100),
    uploaded_at TIMESTAMP,
    uploaded_by BIGINT
);

CREATE TABLE IF NOT EXISTS student_history (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    student_id BIGINT NOT NULL,
    event_type VARCHAR(60) NOT NULL,
    previous_value VARCHAR(500),
    new_value VARCHAR(500),
    note VARCHAR(1000),
    changed_by BIGINT,
    changed_at TIMESTAMP
);

CREATE TABLE IF NOT EXISTS admissions (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    application_no  VARCHAR(50)     NOT NULL UNIQUE,
    student_id      BIGINT,
    applicant_name  VARCHAR(200)    NOT NULL,
    applied_on      DATE            NOT NULL,
    status          VARCHAR(30)     NOT NULL DEFAULT 'PENDING',
    decision_at     TIMESTAMP,
    decision_by     BIGINT,
    decision_note   VARCHAR(1000),
    created_at      TIMESTAMP,
    updated_at      TIMESTAMP
);

CREATE TABLE IF NOT EXISTS student_enrollments (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    student_id BIGINT NOT NULL,
    session_id BIGINT NOT NULL,
    class_id BIGINT NOT NULL,
    section_id BIGINT NOT NULL,
    roll_no VARCHAR(50),
    enrolled_at TIMESTAMP,
    UNIQUE (student_id, session_id)
);

CREATE TABLE IF NOT EXISTS attendance (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    student_id BIGINT NOT NULL,
    session_id BIGINT NOT NULL,
    class_id BIGINT NOT NULL,
    section_id BIGINT NOT NULL,
    attendance_date DATE NOT NULL,
    status VARCHAR(20) NOT NULL,
    marked_by BIGINT,
    marked_by_user_id BIGINT,
    marked_at TIMESTAMP,
    updated_at TIMESTAMP,
    remarks VARCHAR(255),
    is_corrected BOOLEAN NOT NULL DEFAULT FALSE,
    idempotency_key VARCHAR(100),
    UNIQUE (session_id, student_id, attendance_date)
);

CREATE TABLE IF NOT EXISTS attendance_corrections (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    attendance_id BIGINT NOT NULL,
    old_status VARCHAR(20) NOT NULL,
    new_status VARCHAR(20) NOT NULL,
    reason VARCHAR(500) NOT NULL,
    corrected_by BIGINT NOT NULL,
    corrected_at TIMESTAMP
);

CREATE TABLE IF NOT EXISTS attendance_date_locks (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    lock_scope VARCHAR(20) NOT NULL,
    session_id BIGINT,
    attendance_date DATE NOT NULL,
    reason VARCHAR(500) NOT NULL,
    locked_by BIGINT NOT NULL,
    locked_at TIMESTAMP,
    lock_key VARCHAR(80) NOT NULL UNIQUE
);

CREATE TABLE IF NOT EXISTS staff_attendance (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    staff_id BIGINT NOT NULL,
    attendance_date DATE NOT NULL,
