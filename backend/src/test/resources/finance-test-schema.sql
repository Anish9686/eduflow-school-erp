CREATE TABLE IF NOT EXISTS academic_sessions (
    id BIGINT PRIMARY KEY,
    code VARCHAR(30) NOT NULL,
    name VARCHAR(100) NOT NULL,
    start_date DATE NOT NULL,
    end_date DATE NOT NULL,
    is_active BOOLEAN NOT NULL DEFAULT FALSE
);
CREATE TABLE IF NOT EXISTS classes (
    id BIGINT PRIMARY KEY,
    name VARCHAR(50) NOT NULL,
    order_seq INT NOT NULL DEFAULT 0
);
CREATE TABLE IF NOT EXISTS fee_categories (
    id BIGINT PRIMARY KEY,
    name VARCHAR(100) NOT NULL,
    is_active BOOLEAN NOT NULL DEFAULT TRUE
);
CREATE TABLE IF NOT EXISTS students (
    id BIGINT PRIMARY KEY,
    first_name VARCHAR(100) NOT NULL,
    last_name VARCHAR(100),
    user_id BIGINT,
    status VARCHAR(30) NOT NULL DEFAULT 'ACTIVE'
);
CREATE TABLE IF NOT EXISTS student_enrollments (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    student_id BIGINT NOT NULL,
    session_id BIGINT NOT NULL,
    class_id BIGINT NOT NULL
);
CREATE TABLE IF NOT EXISTS fee_structures (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    session_id BIGINT NOT NULL,
    class_id BIGINT NOT NULL,
    category_id BIGINT NOT NULL,
    amount DECIMAL(12,2) NOT NULL,
    due_date DATE,
    effective_from DATE NOT NULL DEFAULT DATE '1970-01-01',
    effective_to DATE,
    frequency VARCHAR(30) NOT NULL DEFAULT 'ONE_TIME',
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    created_by BIGINT
);
CREATE TABLE IF NOT EXISTS fee_structure_items (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    fee_structure_id BIGINT NOT NULL,
    category_id BIGINT NOT NULL,
    item_name VARCHAR(100) NOT NULL,
    amount DECIMAL(12,2) NOT NULL,
    due_date DATE
);
CREATE TABLE IF NOT EXISTS fee_demands (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    student_id BIGINT NOT NULL,
    fee_structure_id BIGINT NOT NULL,
    session_id BIGINT NOT NULL,
    amount_due DECIMAL(12,2) NOT NULL,
    amount_paid DECIMAL(12,2) NOT NULL DEFAULT 0,
    discount_amount DECIMAL(12,2) NOT NULL DEFAULT 0,
    due_date DATE,
    billing_period DATE,
    status VARCHAR(30) NOT NULL DEFAULT 'PENDING',
    updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    UNIQUE (student_id, fee_structure_id, session_id, billing_period)
);
CREATE TABLE IF NOT EXISTS fee_demand_items (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    fee_demand_id BIGINT NOT NULL,
    fee_structure_item_id BIGINT,
    description VARCHAR(200) NOT NULL,
    amount_due DECIMAL(12,2) NOT NULL,
    amount_paid DECIMAL(12,2) NOT NULL DEFAULT 0
);
CREATE TABLE IF NOT EXISTS payments (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    student_id BIGINT NOT NULL,
    demand_id BIGINT,
    session_id BIGINT NOT NULL,
    receipt_no VARCHAR(50) NOT NULL UNIQUE,
    reference_no VARCHAR(80) NOT NULL UNIQUE,
    amount DECIMAL(12,2) NOT NULL,
    payment_method VARCHAR(20) NOT NULL,
    payment_date DATE NOT NULL,
    status VARCHAR(30) NOT NULL DEFAULT 'POSTED',
    remarks VARCHAR(500),
    collected_by BIGINT NOT NULL,
    refunded_by BIGINT,
    refunded_at TIMESTAMP,
    refund_reason VARCHAR(500)
);
CREATE TABLE IF NOT EXISTS receipts (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    payment_id BIGINT NOT NULL UNIQUE,
    receipt_number VARCHAR(50) NOT NULL UNIQUE,
    issued_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    issued_by BIGINT
);
CREATE TABLE IF NOT EXISTS finance_adjustments (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    payment_id BIGINT NOT NULL UNIQUE,
    adjustment_type VARCHAR(20) NOT NULL,
    amount DECIMAL(12,2) NOT NULL,
    reason VARCHAR(500) NOT NULL,
    requested_by BIGINT NOT NULL,
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE IF NOT EXISTS fee_discounts (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    student_id BIGINT NOT NULL,
    demand_id BIGINT NOT NULL,
    amount DECIMAL(12,2) NOT NULL,
    reason VARCHAR(500) NOT NULL,
    requested_by BIGINT NOT NULL,
    approval_status VARCHAR(20) NOT NULL DEFAULT 'PENDING',
    approved_by BIGINT,
    approved_at TIMESTAMP,
    rejection_reason VARCHAR(500),
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE IF NOT EXISTS expenses (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    category VARCHAR(100) NOT NULL,
    description VARCHAR(500) NOT NULL,
    amount DECIMAL(12,2) NOT NULL,
    expense_date DATE NOT NULL,
    vendor VARCHAR(200),
    receipt_url VARCHAR(1000),
    approval_status VARCHAR(20) NOT NULL DEFAULT 'DRAFT',
    requested_by BIGINT NOT NULL,
    approved_by BIGINT,
    approved_at TIMESTAMP,
    rejection_reason VARCHAR(500),
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);
